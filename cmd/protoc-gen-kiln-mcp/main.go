// Command protoc-gen-kiln-mcp is a protoc plugin that generates MCP tool
// definitions (JSON Schemas and dispatch code) from KilnService RPCs annotated
// with kiln.options.v1 MCP options.
package main

import (
	"encoding/json"
	"fmt"
	"path"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"

	optionsv1 "github.com/ursakhiin/kiln/gen/go/kiln/options/v1"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		for _, f := range gen.Files {
			if !f.Generate {
				continue
			}
			if err := generateFile(gen, f); err != nil {
				return err
			}
		}
		return nil
	})
}

// mcpMethod is an annotated RPC together with its MCP tool name.
type mcpMethod struct {
	method *protogen.Method
	tool   string
}

// annotatedMethods returns the methods of s that carry an mcp_tool option.
func annotatedMethods(s *protogen.Service) ([]mcpMethod, error) {
	var out []mcpMethod
	for _, m := range s.Methods {
		opt, _ := proto.GetExtension(m.Desc.Options(), optionsv1.E_McpTool).(*optionsv1.McpTool)
		if opt.GetName() == "" {
			continue
		}
		if m.Desc.IsStreamingClient() || m.Desc.IsStreamingServer() {
			return nil, fmt.Errorf("%s: streaming RPC cannot be an MCP tool", m.Desc.FullName())
		}
		out = append(out, mcpMethod{m, opt.GetName()})
	}
	return out, nil
}

func generateFile(gen *protogen.Plugin, f *protogen.File) error {
	perService := make([][]mcpMethod, len(f.Services))
	found := false
	for i, s := range f.Services {
		ms, err := annotatedMethods(s)
		if err != nil {
			return err
		}
		perService[i] = ms
		found = found || len(ms) > 0
	}
	if !found {
		return nil
	}

	pkg := string(f.GoPackageName) + "mcp"
	g := gen.NewGeneratedFile(
		path.Dir(f.GeneratedFilenamePrefix)+"/"+pkg+"/"+path.Base(f.GeneratedFilenamePrefix)+".mcp.go",
		protogen.GoImportPath(string(f.GoImportPath)+"/"+pkg),
	)
	ctx := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Context", GoImportPath: "context"})
	rawJSON := g.QualifiedGoIdent(protogen.GoIdent{GoName: "RawMessage", GoImportPath: "encoding/json"})
	protoMsg := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Message", GoImportPath: "google.golang.org/protobuf/proto"})

	g.P("// Code generated by protoc-gen-kiln-mcp. DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	g.P("package ", pkg)
	g.P()

	for i, s := range f.Services {
		ms := perService[i]
		if len(ms) == 0 {
			continue
		}
		name := s.GoName
		g.P("// ", name, "ToolHandler has one method per ", name, " RPC with a")
		g.P("// kiln.options.v1.mcp_tool option, in declaration order.")
		g.P("type ", name, "ToolHandler interface {")
		for _, m := range ms {
			g.P(m.method.GoName, "(", ctx, ", *", g.QualifiedGoIdent(m.method.Input.GoIdent), ") (*",
				g.QualifiedGoIdent(m.method.Output.GoIdent), ", error)")
		}
		g.P("}")
		g.P()
		g.P("// ", name, "Tool describes one MCP tool backed by a ", name, " RPC.")
		g.P("type ", name, "Tool struct {")
		g.P("Name string")
		g.P("Description string")
		g.P("InputSchema ", rawJSON)
		g.P("NewRequest func() ", protoMsg)
		g.P("Call func(ctx ", ctx, ", h ", name, "ToolHandler, req ", protoMsg, ") (", protoMsg, ", error)")
		g.P("}")
		g.P()
		g.P("// ", name, "Tools lists the tools in declaration order.")
		g.P("var ", name, "Tools = []", name, "Tool{")
		for _, m := range ms {
			schema, err := inputSchema(m.method.Input)
			if err != nil {
				return fmt.Errorf("%s: %w", m.method.Desc.FullName(), err)
			}
			b, err := json.Marshal(schema)
			if err != nil {
				return err
			}
			in := g.QualifiedGoIdent(m.method.Input.GoIdent)
			g.P("{")
			g.P("Name: ", fmt.Sprintf("%q", m.tool), ",")
			g.P("Description: ", fmt.Sprintf("%q", commentText(m.method.Comments.Leading)), ",")
			g.P("InputSchema: ", rawJSON, "(", fmt.Sprintf("%q", string(b)), "),")
			g.P("NewRequest: func() ", protoMsg, " { return &", in, "{} },")
			g.P("Call: func(ctx ", ctx, ", h ", name, "ToolHandler, req ", protoMsg, ") (", protoMsg, ", error) {")
			g.P("resp, err := h.", m.method.GoName, "(ctx, req.(*", in, "))")
			g.P("if err != nil {")
			g.P("return nil, err")
			g.P("}")
			g.P("return resp, nil")
			g.P("},")
			g.P("},")
		}
		g.P("}")
		g.P()
	}
	return nil
}
